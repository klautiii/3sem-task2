#pragma once
//
// SalesPeriod.h
// Стандартные периоды для отчёта о продажах (задание 5 варианта
// "Магазин обуви": показывать продажи за выбранный период времени).
// Произвольный период "с ... по ..." задаётся двумя датами через
// ShoeStore::GetSalesBetween().
//

/**
 * @brief Временное окно, за которое запрашивается отчёт о продажах,
 *        относительно заданной опорной даты (см. ShoeStore::GetSalesForPeriod).
 */
enum class SalesPeriod {
    Week,   ///< Последние 7 дней вплоть до опорной даты включительно.
    Month,  ///< Последние 30 дней вплоть до опорной даты включительно.
    Year    ///< Последние 365 дней вплоть до опорной даты включительно.
};
