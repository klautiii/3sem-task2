#pragma once
//
// SaleStatus.h
// Результат попытки продажи (задание 4 варианта "Магазин обуви":
// продавать выбранный товар).
//
// Библиотека не печатает сообщений (в ней нет потоков ввода-вывода),
// поэтому ShoeStore::Sell() возвращает значение этого enum, а консольное
// приложение уже само решает, какой текст показать пользователю.
//

/**
 * @brief Итог операции ShoeStore::Sell().
 */
enum class SaleStatus {
    Success,              ///< Продажа проведена: остаток уменьшен, продажа записана в журнал.
    InvalidQuantity,      ///< Количество пар меньше или равно нулю.
    UnknownArticle,       ///< Обуви с таким артикулом нет в магазине.
    SizeNotAvailable,     ///< Обуви такого размера нет в наличии.
    NotEnoughPairs,       ///< Размер есть, но пар меньше, чем запрошено.
    UnknownDiscountCard,  ///< Указан номер дисконтной карты, которой нет в магазине.
};
