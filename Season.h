#pragma once
//
// Season.h
// Сезон, для которого предназначена обувь (по описанию предметной
// области: зимняя, летняя, весна-осень и т.д.).
//
#include <string>
#include <vector>

/**
 * @brief Сезон обуви.
 *
 *        Как и Department, значения пронумерованы начиная с 1 - эти же
 *        числа консольное приложение печатает как номера пунктов меню
 *        выбора сезона.
 */
enum class Season {
    Winter = 1,      ///< Зимняя обувь.
    Summer = 2,      ///< Летняя обувь.
    DemiSeason = 3,  ///< Весна-осень (демисезонная).
    AllSeason = 4,   ///< Всесезонная.
};

/**
 * @brief Возвращает название сезона на русском языке.
 * @param season Сезон.
 * @return Например, "зимняя" для Season::Winter.
 */
std::string SeasonName(Season season);

/**
 * @brief Возвращает список всех сезонов в порядке их номеров.
 * @return Ссылка на неизменяемый список всех значений Season.
 */
const std::vector<Season>& AllSeasons();
