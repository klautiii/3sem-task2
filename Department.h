#pragma once
//
// Department.h
// Отделы магазина обуви (по описанию предметной области: мужская,
// женская, детская, спортивная обувь).
//
#include <string>
#include <vector>

/**
 * @brief Отдел магазина, к которому относится обувь. Каждый
 *        класс-наследник Shoe (MensShoe, WomensShoe, KidsShoe,
 *        SportsShoe) возвращает свой отдел из Shoe::GetDepartment().
 *
 *        Значения пронумерованы начиная с 1: консольное приложение
 *        печатает эти же числа как номера пунктов меню выбора отдела
 *        (static_cast<int>(отдел)), поэтому номер в тексте меню и
 *        значение enum - это одно и то же число, а не два разных.
 */
enum class Department {
    Men = 1,     ///< Мужская обувь.
    Women = 2,   ///< Женская обувь.
    Kids = 3,    ///< Детская обувь.
    Sports = 4,  ///< Спортивная обувь.
};

/**
 * @brief Возвращает название отдела на русском языке.
 * @param department Отдел.
 * @return Например, "Мужская обувь" для Department::Men.
 */
std::string DepartmentName(Department department);

/**
 * @brief Возвращает список всех отделов магазина в порядке их номеров.
 *        Используется, чтобы перебрать отделы (например, вывести меню
 *        выбора отдела) без ручного перечисления значений enum.
 * @return Ссылка на неизменяемый список всех значений Department.
 */
const std::vector<Department>& AllDepartments();
