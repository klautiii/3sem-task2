#pragma once
//
// FormatUtils.h
// Небольшие вспомогательные функции для работы со строками. Не являются
// классом предметной области, поэтому не подпадают под правило "каждый
// класс - в своей паре файлов", но, как и весь остальной код библиотеки,
// не используют потоки ввода-вывода (<iostream>/<fstream>/<sstream>/
// <cstdio>) - только std::string и арифметику.
//
#include <optional>
#include <string>

namespace FormatUtils {

    /**
     * @brief Форматирует дробное число с ровно двумя знаками после
     *        точки (например, 123.5 -> "123.50"), без использования
     *        потоков ввода-вывода. Используется для денежных сумм.
     * @param value Значение для форматирования.
     * @return Отформатированная строка.
     */
    std::string FormatMoney(double value);

    /**
     * @brief Форматирует произвольное дробное число с двумя знаками
     *        после точки (например, высота каблука в см). Форматирование
     *        идентично FormatMoney(), выделено под отдельным именем для
     *        читаемости в местах вызова.
     * @param value Значение для форматирования.
     * @return Отформатированная строка.
     */
    std::string FormatDecimal(double value);

    /**
     * @brief Сравнивает две строки без учёта регистра букв. Работает и с
     *        латиницей (A-Z/a-z), и с русскими буквами (А-Я/а-я). Буквы
     *        Ё/ё при сравнении считаются равными е, поэтому "чёрный" и
     *        "черный" совпадают. Требует, чтобы исходные файлы
     *        компилировались как UTF-8 (флаг /utf-8 в настройках проектов).
     * @param a Первая строка для сравнения.
     * @param b Вторая строка для сравнения.
     * @return true, если @p a и @p b равны без учёта регистра букв.
     */
    bool EqualsIgnoreCase(const std::string& a, const std::string& b);

    /**
     * @brief Убирает пробелы, табуляции и символы перевода строки
     *        (\r, \n) в начале и в конце строки.
     * @param s Исходная строка.
     * @return Строка без пробельных символов по краям.
     */
    std::string Trim(const std::string& s);

    /**
     * @brief Безопасно превращает текст, введённый пользователем, в
     *        неотрицательное целое число. В отличие от std::stoi никогда
     *        не бросает исключений и не допускает переполнения: строка
     *        принимается, только если (после Trim) она непустая, состоит
     *        из одних цифр и содержит не больше 9 цифр.
     * @param text Текст для разбора (например, строка, прочитанная из консоли).
     * @return Число, либо std::nullopt, если текст не является корректным
     *         неотрицательным целым.
     */
    std::optional<int> TryParseNonNegativeInt(const std::string& text);

}
